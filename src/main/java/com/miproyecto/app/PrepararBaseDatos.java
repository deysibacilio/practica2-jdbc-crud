package com.miproyecto.app;

import com.miproyecto.db.Db;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;

public class PrepararBaseDatos {
    public static void main(String[] args) {
        try (Connection coneccion = Db.getConnection();
            Statement st = coneccion.createStatement()) {
            System.out.println("Conexión exitosa");

            String sqlCrearAutor = "CREATE TABLE IF NOT EXISTS autor(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(200) NOT NULL UNIQUE);";
            st.executeUpdate(sqlCrearAutor);
            System.out.println("Tabla autor preparada");

            String sqlAgregarAutorId = "ALTER TABLE libro ADD COLUMN IF NOT EXISTS autor_id INTEGER REFERENCES autor(id)";
            st.executeUpdate(sqlAgregarAutorId);

            String sqlInsertarAutor = "INSERT INTO autor (nombre) VALUES(?) ON CONFLICT (nombre) DO NOTHING";
            String sqlRelacionarAutorLibro = "UPDATE libro SET autor_id=(SELECT id FROM autor WHERE nombre = ?) WHERE isbn = ?";

            try(PreparedStatement ps = coneccion.prepareStatement(sqlInsertarAutor)) {
                sqlInsertarAutor(ps, "J. R. R. Tolkien");
                sqlInsertarAutor(ps, "J. K. Rowling");
                sqlInsertarAutor(ps, "Ken Follett");
            }
            try(PreparedStatement ps = coneccion.prepareStatement(sqlRelacionarAutorLibro)) {
                sqlRelacionarAutorLibro(ps, "J. R. R. Tolkien", "9780201633610");
                sqlRelacionarAutorLibro(ps, "J. K. Rowling", "9780132350884");
                sqlRelacionarAutorLibro(ps, "Ken Follett", "9780134685991");
            }
            System.out.println("Preparación terminada");
        } catch (SQLException e){
            throw new RuntimeException("No se pudo preparar la base de datos", e);
        }
    }
    private static void sqlInsertarAutor(PreparedStatement ps, String nombre) throws SQLException{
        ps.setString(1, nombre);
        ps.executeUpdate();
    }
    private static void sqlRelacionarAutorLibro(PreparedStatement ps, String autor, String isbn) throws SQLException{
        ps.setString(1, autor);
        ps.setString(2, isbn);
        int filasActualizadas = ps.executeUpdate();

        if (filasActualizadas == 0){
            System.err.println("No se encontro el libro con el ISBN " + isbn);
        } else {
            System.out.println("Se actualizó " + filasActualizadas + " fila " + " con el ISBN " + isbn);
        }
    }
}
